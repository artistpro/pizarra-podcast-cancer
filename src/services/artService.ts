/**
 * Obtiene el día del año (1-366)
 */
function getDayOfYear(date: Date = new Date()): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

/**
 * Genera la galería diaria activa de 8 obras:
 * - 4 de la Comunidad de Sanantes y Arte-Terapia
 * - 4 de Grandes Maestros del Impresionismo y Luz
 * 
 * Desplaza 2 obras por banco cada 24 horas (4 renovadas diariamente, 4 conservadas).
 */
export function getDailyArtGallery(dayNum?: number): ArtCard[] {
  const day = dayNum ?? getDayOfYear();
  const cLen = COMMUNITY_ART_BANK.length;
  const mLen = MASTERS_ART_BANK.length;

  const cOffset = (day * 2) % cLen;
  const mOffset = (day * 2) % mLen;

  const selectedCommunity: ArtCard[] = [];
  const selectedMasters: ArtCard[] = [];

  for (let i = 0; i < 4; i++) {
    selectedCommunity.push(COMMUNITY_ART_BANK[(cOffset + i) % cLen]);
    selectedMasters.push(MASTERS_ART_BANK[(mOffset + i) % mLen]);
  }

  // Entrelazar armónicamente: Comunidad, Maestro, Comunidad, Maestro...
  const gallery: ArtCard[] = [];
  for (let i = 0; i < 4; i++) {
    gallery.push(selectedCommunity[i]);
    gallery.push(selectedMasters[i]);
  }

  return gallery;
}
